"""PostgreSQL 建表 DDL 集中管理（DAO 只调用，不拼 SQL）。

规范（规则 06 §2）：db/ 是唯一 SQL 出口，DDL 只在本文件，DAO 层只调用不拼接。
表：
- sessions(id TEXT PK, title, is_pinned, context_used, created_at, updated_at) — 会话元数据
- messages(id IDENTITY PK, session_id FK, role, content, created_at) — 消息流
- providers(id IDENTITY PK, slug UNIQUE, name, base_url, api_key_env, is_active, sort_order)
- models(id IDENTITY PK, provider_id FK, name, is_default, is_active, sort_order, 单价)
- mcp_servers / installed_skills — 外部 MCP 与 Skill Market 安装记录
- settings(key PK, value, updated_at) — 系统配置 key/value
- token_cost_ledger / cost_alerts — 成本流水与软告警
- 索引：messages(session_id)、messages(session_id, created_at)、models(provider_id)、
        installed_skills(source)、token_cost_ledger(session_id)、cost_alerts(session_id)

方言要点（2026-10-15 PG 迁移，自 SQLite 转写）：
- `INTEGER PRIMARY KEY AUTOINCREMENT` → `GENERATED BY DEFAULT AS IDENTITY`
- `REAL` → `DOUBLE PRECISION`（SQLite 的 REAL 本就是 8 字节双精度；PG 的 REAL
  只是 float4，照搬会掉精度——金额/成本列尤其不可）
- 原 `PRAGMA journal_mode=WAL` / `foreign_keys=ON` 删除：PG 无 WAL 开关，
  外键约束默认强制
- 布尔位（is_pinned / is_active / is_default）保持 INTEGER 0/1 语义不变，
  避免连带改 repository 的 `bool(row[...])` / `int(flag)` 转换
"""

from __future__ import annotations

from psycopg import AsyncConnection

# 建表 DDL（按序执行：被引用的表先建，满足外键依赖）
_SCHEMA_STATEMENTS: tuple[str, ...] = (
    # 会话表（短期记忆地基；is_pinned：置顶 P0；context_used：上下文用量 2026-08-04）
    """
    CREATE TABLE IF NOT EXISTS sessions (
        id           TEXT PRIMARY KEY,
        title        TEXT NOT NULL DEFAULT '新会话',
        is_pinned    INTEGER NOT NULL DEFAULT 0,
        context_used INTEGER NOT NULL DEFAULT 0,
        created_at   TEXT NOT NULL,
        updated_at   TEXT NOT NULL
    )
    """,
    # 消息表（长期记忆地基）
    """
    CREATE TABLE IF NOT EXISTS messages (
        id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id  TEXT NOT NULL,
        role        TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system', 'tool')),
        content     TEXT NOT NULL,
        created_at  TEXT NOT NULL,
        FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE CASCADE
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_messages_session ON messages(session_id)",
    "CREATE INDEX IF NOT EXISTS idx_messages_session_created "
    "ON messages(session_id, created_at)",
    # 厂商配置（模型元数据真相源；API key 不入库，按 api_key_env 读 .env）
    """
    CREATE TABLE IF NOT EXISTS providers (
        id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug        TEXT NOT NULL UNIQUE,
        name        TEXT NOT NULL,
        base_url    TEXT NOT NULL,
        api_key_env TEXT NOT NULL,
        is_active   INTEGER NOT NULL DEFAULT 1,
        sort_order  INTEGER NOT NULL DEFAULT 0,
        created_at  TEXT NOT NULL,
        updated_at  TEXT NOT NULL
    )
    """,
    # 模型配置（provider 下具体模型，二级选择）
    """
    CREATE TABLE IF NOT EXISTS models (
        id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        provider_id  INTEGER NOT NULL,
        name         TEXT NOT NULL,
        is_default   INTEGER NOT NULL DEFAULT 0,
        is_active    INTEGER NOT NULL DEFAULT 1,
        sort_order   INTEGER NOT NULL DEFAULT 0,
        input_price  DOUBLE PRECISION NOT NULL DEFAULT 0,  -- 元/千 token 输入
        output_price DOUBLE PRECISION NOT NULL DEFAULT 0,  -- 元/千 token 输出
        created_at   TEXT NOT NULL,
        updated_at   TEXT NOT NULL,
        FOREIGN KEY (provider_id) REFERENCES providers(id) ON DELETE CASCADE,
        UNIQUE(provider_id, name)
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_models_provider ON models(provider_id)",
    # 外部 MCP server 连接配置（McpClientManager 消费；stdio 时 url 为空）
    # source/source_url/version/installed_at：Skill Market 安装来源追踪
    """
    CREATE TABLE IF NOT EXISTS mcp_servers (
        id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name         TEXT NOT NULL,
        transport    TEXT NOT NULL DEFAULT 'sse',   -- sse / streamable_http / stdio
        url          TEXT NOT NULL DEFAULT '',      -- HTTP endpoint（stdio 时为空）
        command      TEXT NOT NULL DEFAULT '',      -- stdio 可执行文件
        args         TEXT NOT NULL DEFAULT '[]',    -- stdio 参数（JSON 数组）
        headers      TEXT NOT NULL DEFAULT '{}',    -- HTTP headers（JSON，含 auth token）
        is_active    INTEGER NOT NULL DEFAULT 1,
        sort_order   INTEGER NOT NULL DEFAULT 0,
        source       TEXT NOT NULL DEFAULT 'manual',  -- manual / smithery（来源市场）
        source_url   TEXT NOT NULL DEFAULT '',        -- 市场条目页 URL
        version      TEXT NOT NULL DEFAULT '',        -- 版本号（市场 qualifiedName）
        installed_at TEXT NOT NULL DEFAULT '',
        created_at   TEXT NOT NULL,
        updated_at   TEXT NOT NULL
    )
    """,
    # 已安装 Skill 记录（Skill Market 安装管理；mcp_server 与 skill_md 两类共用）
    """
    CREATE TABLE IF NOT EXISTS installed_skills (
        id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name         TEXT NOT NULL,
        skill_type   TEXT NOT NULL DEFAULT 'mcp_server',  -- mcp_server / skill_md
        source       TEXT NOT NULL DEFAULT 'manual',      -- manual / smithery
        source_url   TEXT NOT NULL DEFAULT '',
        version      TEXT NOT NULL DEFAULT '',
        install_path TEXT NOT NULL DEFAULT '',  -- skill_md 目录 / mcp_server 的 mcp_servers.id
        is_active    INTEGER NOT NULL DEFAULT 1,
        created_at   TEXT NOT NULL,
        updated_at   TEXT NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_skills_source ON installed_skills(source)",
    # MCP 工具的**治理元数据**（2026-10-15 设计-工具动态注册两方案对比 §8.1）
    #
    # 为什么本地存：MCP 标准**不自带**风险等级 / HITL 审批策略——让远端返回等于
    # 自定义扩展协议（换服务即崩）；不治理则是安全漏洞（高危外部工具绕开审批）。
    # 故治理声明**留在本地**，第三方 server 只管干活，安全边界清晰（拍板 D2 选①）。
    #
    # 匹配键 = (server_name, tool_name)：tool_name 存**远端原名**（不含 server 前缀），
    # 挂载名由 `McpToolPolicy.qualified_name` 算出（与 tool_name_prefix=True 对齐）——
    # 存原名而非拼好的全名，改前缀配置时旧记录不失效（定案 X2）。
    #
    # ⚠️ 未在本表登记的工具**不挂载**（默认拒绝，定案 X1；同 channels/base.py
    #    「占位不得假装通过」的 fail-closed 哲学）。
    """
    CREATE TABLE IF NOT EXISTS mcp_tool_meta (
        id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        server_name       TEXT NOT NULL,                        -- 关联 mcp_servers.name
        tool_name         TEXT NOT NULL,                        -- 远端原始工具名
        risk_level        TEXT NOT NULL DEFAULT 'low',          -- low / medium / high
        requires_approval INTEGER NOT NULL DEFAULT 0,
        allowed_decisions TEXT NOT NULL DEFAULT '[]',           -- JSON 数组（同 ToolSpec 口径）
        is_idempotent     INTEGER NOT NULL DEFAULT 0,           -- 重试门控
        retry             TEXT NOT NULL DEFAULT '',             -- JSON {retries,delays}；空=不重试
        note              TEXT NOT NULL DEFAULT '',
        created_at        TEXT NOT NULL,
        updated_at        TEXT NOT NULL,
        UNIQUE (server_name, tool_name)
    )
    """,
    # 系统配置（key/value，2026-08-04 后端开发计划 P1：设置页开关持久化）
    """
    CREATE TABLE IF NOT EXISTS settings (
        key        TEXT PRIMARY KEY,
        value      TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )
    """,
    # 成本流水（2026-08-11 成本控制 §5.1 D1）：每次图执行一条，可审计可汇总
    """
    CREATE TABLE IF NOT EXISTS token_cost_ledger (
        id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id    TEXT NOT NULL,
        model_id      INTEGER NOT NULL,
        input_tokens  INTEGER NOT NULL DEFAULT 0,
        output_tokens INTEGER NOT NULL DEFAULT 0,
        input_cost    DOUBLE PRECISION NOT NULL DEFAULT 0,
        output_cost   DOUBLE PRECISION NOT NULL DEFAULT 0,
        total_cost    DOUBLE PRECISION NOT NULL DEFAULT 0,
        created_at    TEXT NOT NULL,
        FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE CASCADE
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_cost_ledger_session ON token_cost_ledger(session_id)",
    # 成本告警（2026-08-11 成本控制 §5.4 D4）：预算软告警落库留痕
    """
    CREATE TABLE IF NOT EXISTS cost_alerts (
        id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id TEXT NOT NULL,
        threshold  DOUBLE PRECISION NOT NULL,
        total_cost DOUBLE PRECISION NOT NULL,
        message    TEXT NOT NULL,
        created_at TEXT NOT NULL,
        FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE CASCADE
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_cost_alerts_session ON cost_alerts(session_id)",
    # 审计事件（2026-10-16 设计-审计与可观测 §5.3）：JSONL 是**权威底账**，
    # 本表是**派生索引**——可随时由 `rebuild_from_jsonl()` 重建。
    #
    # 结构口径：**核心字段建列**（要按它查/排序/去重）+ 层自有字段进 payload JSONB
    # （各层字段各不相同，全展开会变成"每加一层就改表"的宽表）。
    #
    # `UNIQUE (trace_id, seq)` 是**重放幂等的依据**——重放可安全重复执行。
    """
    CREATE TABLE IF NOT EXISTS audit_events (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        trace_id   TEXT        NOT NULL,
        seq        INTEGER     NOT NULL,
        ts         TIMESTAMPTZ NOT NULL,
        layer      TEXT        NOT NULL,
        event      TEXT        NOT NULL,
        status     TEXT,
        session_id TEXT,
        orphan     BOOLEAN     NOT NULL DEFAULT FALSE,
        payload    JSONB       NOT NULL DEFAULT '{}'::jsonb,
        UNIQUE (trace_id, seq)
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_audit_session ON audit_events (session_id, ts DESC)",
    "CREATE INDEX IF NOT EXISTS idx_audit_layer ON audit_events (layer, ts DESC)",
    "CREATE INDEX IF NOT EXISTS idx_audit_trace ON audit_events (trace_id)",
)

# 旧库加列（PG 有 ADD COLUMN IF NOT EXISTS，无需 try/except 吞错实现幂等）
# 新库走 CREATE TABLE 已含全部列，这里是「既有 PG 库升级」路径
_MCP_SERVERS_NEW_COLUMNS: tuple[tuple[str, str], ...] = (
    ("source", "TEXT NOT NULL DEFAULT 'manual'"),
    ("source_url", "TEXT NOT NULL DEFAULT ''"),
    ("version", "TEXT NOT NULL DEFAULT ''"),
    ("installed_at", "TEXT NOT NULL DEFAULT ''"),
)

_SESSIONS_NEW_COLUMNS: tuple[tuple[str, str], ...] = (
    ("is_pinned", "INTEGER NOT NULL DEFAULT 0"),
    ("context_used", "INTEGER NOT NULL DEFAULT 0"),
)

_MODELS_NEW_COLUMNS: tuple[tuple[str, str], ...] = (
    ("input_price", "DOUBLE PRECISION NOT NULL DEFAULT 0"),
    ("output_price", "DOUBLE PRECISION NOT NULL DEFAULT 0"),
)

# (表名, 待确保存在的列)
_COLUMN_MIGRATIONS: tuple[tuple[str, tuple[tuple[str, str], ...]], ...] = (
    ("mcp_servers", _MCP_SERVERS_NEW_COLUMNS),
    ("sessions", _SESSIONS_NEW_COLUMNS),
    ("models", _MODELS_NEW_COLUMNS),
)


async def init_schema(conn: AsyncConnection) -> None:
    """幂等执行建表 DDL + 旧库加列（可反复调用）。

    Args:
        conn: PG 连接（连接层借出，行工厂 dict_row）

    Raises:
        psycopg.Error: 建表失败（连接已关闭 / 权限不足 / DDL 语法错）
    """
    for statement in _SCHEMA_STATEMENTS:
        await conn.execute(statement)
    for table, columns in _COLUMN_MIGRATIONS:
        await _ensure_columns(conn, table, columns)
    await conn.commit()


async def _ensure_columns(
    conn: AsyncConnection,
    table: str,
    columns: tuple[tuple[str, str], ...],
) -> None:
    """确保表已含指定列（ADD COLUMN IF NOT EXISTS，幂等）。

    Args:
        conn: PG 连接
        table: 目标表名（本模块内常量，非外部输入）
        columns: (列名, 列定义) 序列
    """
    for col_name, col_def in columns:
        await conn.execute(
            f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {col_name} {col_def}"
        )
